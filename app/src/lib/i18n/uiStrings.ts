export type UiLang = UiLocaleCode;

export const UI_LANG_OPTIONS = [...UI_LOCALE_LANGUAGES];

export function isUiLang(s: string): s is UiLang {
  return (UI_LOCALE_CODES as readonly string[]).includes(s);
}

/** `<option>` text for report/output languages, spelled in the active UI locale (CLDR via Intl). */
export function reportLanguageOptionLabel(lang: UiLang, code: ReportLanguageCode): string {
  try {
    const chain = [UI_LOCALE_BCP47[lang], "en"];
    const dn = new Intl.DisplayNames(chain, { type: "language" });
    const name = dn.of(code);
    if (name) return name;
  } catch {
    /* ignore */
  }
  return languageLabel(code);
}

/**
 * Language name written in that language (endonym), for UI locale `<option>` labels:
 * English → English, Spanish → Español, etc. CLDR via Intl; first letter title-cased when lowercase.
 */
export function uiLanguageNativeLabel(code: UiLang): string {
  try {
    const tag = UI_LOCALE_BCP47[code];
    const dn = new Intl.DisplayNames([tag, code], { type: "language" });
    const raw = dn.of(code);
    if (raw) {
      const chars = [...raw];
      const first = chars[0];
      if (first && /\p{Ll}/u.test(first)) {
        return first.toLocaleUpperCase(tag) + chars.slice(1).join("");
      }
      return raw;
    }
  } catch {
    /* ignore */
  }
  return languageLabel(code);
}

