/** Class default may be a preset code or a custom subject name from the school list. */
export function defaultSubjectDisplayLocalized(lang: UiLang, stored: string): string {
  const s = stored.trim();
  if (!s) return subjectLabelLocalized(lang, "efl");
  const low = s.toLowerCase();
  if (low === "subject to be defined") return translate(lang, "class.subjectToBeDefinedLabel");
  if (isSubjectCode(low)) return subjectLabelLocalized(lang, low);
  return s;
}

/**
 * In-app label for the class default subject when unset or still the legacy generic `efl`.
 * Parent PDFs continue to use {@link defaultSubjectDisplayLocalized} / {@link resolvedSubjectLabelForPdf}.
 */
export function classDefaultSubjectUiLine(lang: UiLang, stored: string): string {
  const s = stored.trim();
  if (!s || s.toLowerCase() === "efl") return translate(lang, "tenant.defineSubjectNamePlaceholder");
  const low = s.toLowerCase();
  if (low === "subject to be defined") return translate(lang, "class.subjectToBeDefinedLabel");
  if (isSubjectCode(low)) return subjectLabelLocalized(lang, low);
  return s;
}

/** Dropdown / read-only label for stored class level (CEFR + tag, or translated year group). */
export function formatClassLevelOptionLabel(lang: UiLang, stored: string, rubric: GradeRubricProfile): string {
  const s = stored.trim();
  if (!s) return "";
  if (rubric === "language" && (CLASS_CEFR_CODES as readonly string[]).includes(s)) {
    return `${s} (${translate(lang, "class.levelFrameworkTag")})`;
  }
  const m = /^Year (\d+)$/.exec(s);
  if (m) return translate(lang, "class.yearGroupLabel", { n: m[1] });
  return s;
}

/** Subject line on parent PDFs (output-language locale; preset vs custom class default). */
export function resolvedSubjectLabelForPdf(lang: UiLang, inputs: ReportInputs, classDefault: string): string {
  if (inputs.subject_code) return subjectLabelLocalized(lang, inputs.subject_code);
  return defaultSubjectDisplayLocalized(lang, classDefault);
}
